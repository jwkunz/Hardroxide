pub fn hls_example(m: &Model, crate_name: &str) -> Option<String> {
    let i = m.insts.iter().find(|i| i.generated.is_some())?;
    let mut s = example_header(
        &format!(
            "Hardware smoke test for `{}`: prints the control block and every readable user register. Does not start the core.",
            i.inst.name
        ),
        crate_name,
    );
    let _ = writeln!(
        s,
        "fn main() -> ! {{\n{INIT}    let ip = &d.{};\n    println!(\"idle={{}} ready={{}} done={{}}\", ip.is_idle().unwrap(), ip.is_ready().unwrap(), ip.is_done().unwrap());",
        i.ident
    );
    for r in i
        .regs
        .iter()
        .filter(|r| r.reg.offset >= 0x10 && r.reg.access != hardroxide_hwh::Access::WriteOnly)
    {
        let _ = writeln!(
            s,
            "    println!(\"{} = {{:#x}}\", ip.{}().unwrap());",
            r.reg.name, r.ident
        );
    }
    let _ = writeln!(s, "    halt()\n}}");
    Some(s)
}

/// Waits for a timer interrupt through the GIC, three times: the PL-to-PS interrupt path.
pub fn timer_irq_example(m: &Model, d: &Design, crate_name: &str) -> Option<String> {
    let i = m.insts.iter().find(|i| {
        i.driver.as_deref() == Some("hardroxide_ip::timer::AxiTimer")
            && irq_lines(i, d)
                .iter()
                .any(|l| l.via_intc.is_none() && l.gic_spi.is_some())
    })?;
    let l = irq_lines(i, d)
        .into_iter()
        .find(|l| l.via_intc.is_none() && l.gic_spi.is_some())?;
    let lib = crate_name.replace('-', "_");
    let mut s = example_header(
        &format!(
            "Interrupt test for `{}`: starts a one-shot 50 ms timer and waits for its interrupt through the GIC, three times.",
            i.inst.name
        ),
        crate_name,
    );
    let _ = writeln!(
        s,
        "use core::time::Duration;\nuse hardroxide_irq::IrqWaiter;\nuse hardroxide_mmio::time::Instant;\nuse ps7::wait::IrqWait;\n\nfn main() -> ! {{\n{INIT}    let t = &d.{id};\n    let irq = IrqWait::for_line(&{lib}::pac::{id}::{k}).expect(\"interrupt reaches the PS\");\n    d.enable_interrupts();\n    for round in 0..3 {{\n        t.clear().unwrap();\n        irq.enable().unwrap();\n        let t0 = Instant::now();\n        t.start(t.ticks_for_ns(50_000_000) as u32, false, true).unwrap();\n        let ev = irq.wait_event(Some(Duration::from_secs(2))).unwrap();\n        println!(\"round {{round}}: event {{ev:?}} after {{}} us\", t0.elapsed().as_micros());\n        t.clear().unwrap();\n    }}\n    halt()\n}}",
        id = i.ident,
        k = l.konst
    );
    Some(s)
}
