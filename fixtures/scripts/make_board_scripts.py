#!/usr/bin/env python3
"""Derive board-accurate variants of the fixture build scripts.

The fixtures are built without a board preset, so their `ps7_init` leaves MIO, UART, DDR
timing and most peripherals unconfigured; that is fine under Linux (U-Boot initialises the
PS) but not for bare metal, which needs the real configuration to get a console.

This reads the PS7 settings of the PYNQ base overlay (fixtures/real/pynq_base_overlay.xsa,
Apache-2.0, built by the PYNQ project for this board) and writes
  board/pynq_z2_ps7_board.tcl        the preset (a proc applied to the PS7 cell)
  board/build_pynq_z2_<name>.tcl     each fixture script with the preset applied right after
                                     the script's own PS7 settings
Only the PS-side settings are copied; everything that shapes the PL interface (ports, clocks
to the PL, interrupts, AXI HP/GP use) stays as the fixture script sets it.
"""
import re, sys, zipfile, glob, os
import xml.etree.ElementTree as ET

here = os.path.dirname(os.path.abspath(__file__))
xsa = os.path.join(here, "../real/pynq_base_overlay.xsa")
root = ET.fromstring(zipfile.ZipFile(xsa).read("design_1.hwh"))
ps7 = next(m for m in root.find("MODULES").findall("MODULE") if m.get("MODTYPE") == "processing_system7")
params = {p.get("NAME"): p.get("VALUE") for p in ps7.find("PARAMETERS").findall("PARAMETER")}

# Settings that shape the PL interface, or are computed by Vivado: leave to the fixture script.
skip = re.compile(
    r"^PCW_(USE_|EN_CLK|EN_RST|FPGA|FCLK|ACT_|S_AXI_|M_AXI_|IRQ_|EN_EMIO|FTM_|PRESET_BANK|TPIU_|TRACE|"
    r"CORE0_|CORE1_|EN_DDR|NUM_FABRIC|P2F_|QOS_|DDR_PORT|DDR_HPRLPR|EXACT_FREQ|OVERRIDE_BASIC_CLK|"
    r"DDR_RAM_|MIO_PRIMITIVE|MIO_TREE_|PJTAG|SD1_|GPIO_EMIO)")
keep = {k: v for k, v in sorted(params.items())
        if k.startswith("PCW_") and not skip.match(k) and v not in (None, "", "<Select>")}

out = ["# Generated by make_board_scripts.py from the PYNQ base overlay's PS7 settings (Apache-2.0).",
       "# Applies the PYNQ-Z2 board's PS configuration (DDR, MIO, peripherals) to a PS7 cell.",
       "proc apply_pynq_z2_ps7 {ps} {", "    set failed 0", "    foreach {k v} {"]
for k, v in keep.items():
    out.append("        %s {%s}" % (k, v.replace("{", "\\{").replace("}", "\\}")))
out += ["    } {", "        if {[catch {set_property CONFIG.$k $v $ps} err]} { incr failed }", "    }",
        "    puts \"pynq_z2 PS7 preset: applied, $failed setting(s) rejected\"", "}", ""]
os.makedirs(os.path.join(here, "board"), exist_ok=True)
open(os.path.join(here, "board/pynq_z2_ps7_board.tcl"), "w").write("\n".join(out))
print(f"{len(keep)} PS7 settings of {len(params)} kept")

for f in sorted(glob.glob(os.path.join(here, "build_pynq_z2_*.tcl"))):
    name = os.path.basename(f)
    t = open(f).read()
    m = re.search(r"(set ps \[create_bd_cell[^\n]*\n(?:[^\n]*\n)*?[^\n]*\] \$ps\n)", t)
    if not m:
        print("no PS block in", name); continue
    inject = ("\n# Board-accurate PS configuration (DDR, MIO, UART, ...): see make_board_scripts.py\n"
              "source [file join [file dirname [info script]] pynq_z2_ps7_board.tcl]\napply_pynq_z2_ps7 $ps\n")
    t = t[:m.end()] + inject + t[m.end():]
    open(os.path.join(here, "board", name), "w").write(t)
    print("wrote board/" + name)
