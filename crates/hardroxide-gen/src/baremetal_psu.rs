/// A Zynq-7000 bare-metal example, for this family: the examples differ only in the processor crate they name.
fn for_psu(example: String) -> String {
    example
        .replace("halt, ps7}", "halt, psu}")
        .replace("ps7::", "psu::")
}

/// The example programs, as `(name, source)`.
pub fn examples(
    m: &Model,
    d: &Design,
    crate_name: &str,
    rtos: bool,
) -> Vec<(&'static str, String)> {
    if rtos {
        // Programs that use the kernel; examples that use the default interrupt entries would not link here.
        return vec![("rt_control", for_psu(baremetal::rt_example(crate_name)))];
    }
    [
        (
            "board_check",
            Some(baremetal::board_check_example(m, d, crate_name)),
        ),
        ("gpio_smoke", baremetal::gpio_example(m, crate_name)),
        ("timer_delay", baremetal::timer_example(m, crate_name)),
        ("timer_irq", baremetal::timer_irq_example(m, d, crate_name)),
        ("bram_test", baremetal::bram_example(m, crate_name)),
        ("hls_smoke", baremetal::hls_example(m, crate_name)),
        ("dma_loopback", baremetal::dma_example(m, crate_name)),
    ]
    .into_iter()
    .filter_map(|(name, text)| Some((name, for_psu(text?))))
    .collect()
}
