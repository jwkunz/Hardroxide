const INIT: &str = "    let d = match Design::init() {\n        Ok(d) => d,\n        Err(e) => {\n            println!(\"Design::init failed: {e}\");\n            halt()\n        }\n    };\n";

/// Prints the clocks and interrupt routing and compares the PL clocks with the design.
/// Touches no IP register.
pub fn board_check_example(m: &Model, d: &Design, crate_name: &str) -> String {
    let mut s = example_header(
        "First on-board check: prints the clocks and the interrupt routing and compares the\n//! PL clocks with the design. Touches no IP register, so it cannot hang on a faulty IP.",
        crate_name,
    );
    let lib = crate_name.replace('-', "_");
    let _ = writeln!(
        s,
        "fn main() -> ! {{\n{INIT}    println!(\"\\n== board check ({lib}) ==\");\n    println!(\"PL configured, interface {{}}\", {lib}::INTERFACE_HASH.trim());\n    let mut failed = 0;\n    for &(i, want) in {lib}::FCLKS {{\n        match d.fclk_hz(i) {{\n            Ok(got) if got.abs_diff(want) * 100 <= want => println!(\"FCLK{{i}}: {{got}} Hz (want {{want}}) ok\"),\n            Ok(got) => {{\n                println!(\"FCLK{{i}}: {{got}} Hz (want {{want}}) MISMATCH\");\n                failed += 1;\n            }}\n            Err(e) => {{\n                println!(\"FCLK{{i}}: {{e}}\");\n                failed += 1;\n            }}\n        }}\n    }}"
    );
    let any = m.insts.iter().any(|i| {
        irq_lines(i, d)
            .iter()
            .any(|l| l.via_intc.is_none() && l.gic_spi.is_some())
    });
    if any {
        let _ = writeln!(
            s,
            "    for l in {lib}::IRQ_LINES {{\n        println!(\"irq {{}}.{{}} -> GIC id {{}} ({{}})\", l.instance, l.port, 32 + l.gic_spi.unwrap_or(0), if l.edge {{ \"rising edge\" }} else {{ \"level\" }});\n    }}"
        );
    }
    let _ = writeln!(
        s,
        "    if failed > 0 {{\n        println!(\"{{failed}} check(s) failed\");\n    }} else {{\n        println!(\"all checks passed; next run the per-IP examples\");\n    }}\n    halt()\n}}"
    );
    s
}

pub fn gpio_example(m: &Model, crate_name: &str) -> Option<String> {
    let mut all = all_with(m, "::AxiGpio");
    let param = |i: &Inst, k: &str, d: &str| {
        i.inst
            .parameters
            .get(k)
            .cloned()
            .unwrap_or_else(|| d.into())
    };
    let has_out = |i: &Inst| param(i, "C_ALL_INPUTS", "0") != "1";
    all.sort_by_key(|i| !has_out(i));
    let i = all.first()?;
    let w1: u32 = param(i, "C_GPIO_WIDTH", "32")
        .parse()
        .unwrap_or(32)
        .clamp(1, 32);
    let in2 = param(i, "C_IS_DUAL", "0") == "1" && param(i, "C_ALL_INPUTS_2", "0") == "1";
    let mut s = example_header(
        &format!(
            "Hardware smoke test for `{}`: walks a one-hot pattern over channel 1 (if it has\n//! outputs; otherwise reads it) and prints channel 2. To use another GPIO, change the field.",
            i.inst.name
        ),
        crate_name,
    );
    let _ = writeln!(
        s,
        "use core::time::Duration;\nuse hardroxide_ip::gpio::Channel;\nuse hardroxide_mmio::time::sleep;\n\nfn main() -> ! {{\n{INIT}    let gpio = &d.{};",
        i.ident
    );
    if has_out(i) {
        let _ = writeln!(
            s,
            "    gpio.set_input_mask(Channel::One, 0).unwrap(); // all outputs\n    for step in 0..{} {{\n        gpio.write(Channel::One, 1 << (step % {w1})).unwrap();",
            w1 * 2
        );
        if in2 {
            let _ = writeln!(
                s,
                "        println!(\"channel 2 inputs: {{:#x}}\", gpio.read(Channel::Two).unwrap());"
            );
        }
        let _ = writeln!(
            s,
            "        sleep(Duration::from_millis(250));\n    }}\n    gpio.write(Channel::One, 0).unwrap();"
        );
    } else {
        let _ = writeln!(
            s,
            "    println!(\"channel 1: {{:#x}}\", gpio.read(Channel::One).unwrap());"
        );
    }
    let _ = writeln!(s, "    halt()\n}}");
    Some(s)
}

