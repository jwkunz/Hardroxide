//! The bare-metal platform: a `no_std` crate for the Cortex-A9 with no operating system,
//! built on `hardroxide-ps7`. It shares the register layer (`pac`), the driver choices and
//! the HLS wrappers with the Linux platform; the glue differs: no bitstream is embedded
//! (the loader or FSBL configures the PL), interrupts are programmed into the GIC instead
//! of a device-tree overlay, and the examples are `no_std` programs that print on the PS UART.

use crate::Options;
use crate::render::{HEADER, Inst, Model, all_with, ctor, first_with, irq_lines};
use hardroxide_hwh::Design;
use std::fmt::Write;

/// Default RAM for the program: DDR from 1 MiB (the first MiB is left alone) on a 512 MiB
/// board such as the PYNQ-Z2.
const RAM_ORIGIN: u64 = 0x0010_0000;
const RAM_LENGTH: u64 = 0x1FF0_0000;

/// What the design says about the PS side: the clock the PS runs from and the console UART.
pub struct PsInfo {
    pub ps_clk_hz: u64,
    /// Base address of the PS UART to use as console, if the design enables one.
    pub console_uart: Option<u64>,
    pub baud: u32,
}

pub fn ps_info(d: &Design) -> PsInfo {
    let ps = d.instances.iter().find(|i| i.is_ps);
    let p = |k: &str| ps.and_then(|i| i.parameters.get(k)).map(String::as_str);
    let enabled = |u: u32| p(&format!("PCW_UART{u}_PERIPHERAL_ENABLE")) == Some("1");
    let (console_uart, n) = if enabled(0) {
        (Some(0xE000_0000), 0)
    } else if enabled(1) {
        (Some(0xE000_1000), 1)
    } else {
        (None, 0)
    };
    let baud = p(&format!("PCW_UART{n}_BAUD_RATE"))
        .and_then(|b| b.parse().ok())
        .unwrap_or(115_200);
    PsInfo {
        ps_clk_hz: d.ps_clk_hz,
        console_uart,
        baud,
    }
}

pub fn cargo_toml(name: &str, opts: &Options) -> String {
    // The runtime crates are used without `std`; the PS crate keeps its default features
    // (the interrupt and supervisor-call vector entries).
    let dep = |c: &str, extra: &str| {
        let nd = if c == "hardroxide-ps7" {
            ""
        } else {
            ", default-features = false"
        };
        match &opts.hardroxide_path {
            Some(root) => format!(
                "{c} = {{ path = \"{}\"{nd}{extra} }}",
                root.join("crates").join(c).display()
            ),
            None => format!("{c} = {{ version = \"1\"{nd}{extra} }}"),
        }
    };
    format!(
        "# @generated by hardroxide (platform: baremetal).\n[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[dependencies]\n{}\n{}\n{}\n{}\n{}\n{}\n\n[profile.dev]\npanic = \"abort\"\n\n[profile.release]\npanic = \"abort\"\nopt-level = \"s\"\ndebug = true\n",
        dep("hardroxide-mmio", ", features = [\"physmem\"]"),
        dep("hardroxide-fpga", ""),
        dep("hardroxide-ip", ""),
        dep("hardroxide-irq", ""),
        dep("hardroxide-dma", ""),
        dep("hardroxide-ps7", ", features = [\"panic-handler\"]"),
    )
}

