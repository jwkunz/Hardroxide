#!/usr/bin/env python3
"""Backward compatibility with a published release (ADR 0005). Fails if anything a user of that release relies on changed.

Three checks, all against COMPAT_BASE (default 2.7.0), built from the release's git tag (so that they do not depend on
crates.io, where 2.7.0 is yanked):

  semver     every library's public API against the release's (cargo-semver-checks), and for the processor support and
             the kernel also as built for the Zynq-7000 (their Arm-only modules do not exist on a PC)
  generator  the working tree's `hardroxide generate` against the release's CLI, for every XSA that CLI accepts and all
             three platforms: the same files with the same contents (only the version in the dependencies may differ),
             `hardroxide update` accepts a crate the release made, and no command or flag disappeared
  programs   crates generated by the release's CLI, with the programs of that release, built against the working tree's
             libraries (the frozen user project)

Usage: scripts/check-compat.py [semver] [generator] [programs]    (no argument: all three)
Needs: cargo-semver-checks, the armv7a-none-eabihf target, and git with the release's tag.
"""
import difflib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = os.environ.get("COMPAT_BASE", "2.7.0")
TAG = f"v{BASE}"
WORK = ROOT / "target" / "compat"
ARM = "armv7a-none-eabihf"
# The libraries the release published. Crates added later have nothing to be compared with.
LIBS = "audio crypto dma fat fpga gen gfx hwh ip irq mmio net ps7 rt tls video".split()
# Their API also differs by target: (crate, extra features).
ARM_LIBS = [("ps7", ["--features", "net"]), ("rt", [])]
PLATFORMS = ["linux", "baremetal", "rtos"]
failures: list[str] = []


def run(cmd, **kw):
    return subprocess.run([str(c) for c in cmd], capture_output=True, text=True, **kw)


def fail(what, detail=""):
    failures.append(what)
    print(f"FAIL  {what}")
    if detail:
        print("      " + "\n      ".join(detail.strip().splitlines()[-30:]))


def ok(what):
    print(f"ok    {what}")


def release_source() -> Path:
    """The release's sources, taken from its tag."""
    src = WORK / f"source-{BASE}"
    if not (src / ".complete").exists():
        shutil.rmtree(src, ignore_errors=True)
        src.mkdir(parents=True)
        r = run(["bash", "-o", "pipefail", "-c", f"git archive {TAG} | tar -x -C '{src}'"], cwd=ROOT)
        if r.returncode:
            sys.exit(f"cannot read the sources of {TAG} (is the tag fetched?):\n" + r.stderr)
        (src / ".complete").touch()
    return src


# ---- semver ----------------------------------------------------------------------------------------------------------

def semver():
    if not shutil.which("cargo-semver-checks"):
        fail("semver: cargo-semver-checks is not installed (cargo install cargo-semver-checks --locked)")
        return
    cmd = ["cargo", "semver-checks", "--baseline-rev", TAG, "--release-type", "minor"]
    for c in LIBS:
        cmd += ["-p", f"hardroxide-{c}"]
    r = run(cmd, cwd=ROOT)
    if r.returncode == 0:
        ok(f"semver: {len(LIBS)} libraries are compatible with {BASE} (as built for this machine)")
    else:
        fail("semver (host)", r.stdout + r.stderr)

    # cargo-semver-checks cannot build a bare-metal target itself (it silences warnings Cargo's target probe needs),
    # so the API descriptions are generated here and handed to it.
    d = WORK / "semver-arm"
    shutil.rmtree(d, ignore_errors=True)
    (d / "base" / "src").mkdir(parents=True)
    (d / "base" / "src" / "lib.rs").write_text("")
    old_crates = release_source() / "crates"
    deps = "".join(
        f'hardroxide-{c} = {{ path = "{old_crates / ("hardroxide-" + c)}"' + (f", features = [\"{f[1]}\"]" if f else "") + " }\n"
        for c, f in ARM_LIBS
    )
    (d / "base" / "Cargo.toml").write_text(
        f'[package]\nname = "baseline"\nversion = "0.0.0"\nedition = "2024"\npublish = false\n[dependencies]\n{deps}[workspace]\n'
    )
    env = dict(os.environ, RUSTC_BOOTSTRAP="1")
    tail = ["--lib", "--target", ARM, "--", "-Z", "unstable-options", "--output-format", "json"]
    for c, features in ARM_LIBS:
        doc = f"hardroxide_{c}.json"
        old = run(["cargo", "rustdoc", "-q", "-p", f"hardroxide-{c}@{BASE}", "--target-dir", d / "base-target"] + tail, cwd=d / "base", env=env)
        new = run(["cargo", "rustdoc", "-q", "-p", f"hardroxide-{c}", "--target-dir", d / "cur-target"] + features + tail, cwd=ROOT, env=env)
        if old.returncode or new.returncode:
            fail(f"semver ({ARM}): could not document hardroxide-{c}", old.stderr + new.stderr)
            continue
        r = run(["cargo", "semver-checks", "--release-type", "minor",
                 "--baseline-rustdoc", d / "base-target" / ARM / "doc" / doc,
                 "--current-rustdoc", d / "cur-target" / ARM / "doc" / doc])
        if r.returncode == 0:
            ok(f"semver: hardroxide-{c} as built for {ARM} is compatible with {BASE}")
        else:
            fail(f"semver: hardroxide-{c} ({ARM})", r.stdout + r.stderr)


# ---- generator -------------------------------------------------------------------------------------------------------

def old_cli() -> Path:
    root = WORK / f"cli-{BASE}"
    exe = root / "bin" / "hardroxide"
    if not exe.exists():
        print(f"building hardroxide-cli {BASE} from {TAG} ...")
        r = run(["cargo", "install", "--path", release_source() / "crates" / "hardroxide-cli", "--locked", "--root", root,
                 "--target-dir", WORK / "cli-target"])
        if r.returncode:
            sys.exit("could not build the release's CLI:\n" + r.stderr)
    return exe


def new_cli() -> Path:
    r = run(["cargo", "build", "-q", "-p", "hardroxide-cli"], cwd=ROOT)
    if r.returncode:
        sys.exit("the working tree's CLI does not build:\n" + r.stderr)
    return ROOT / "target" / "debug" / "hardroxide"


def normalise(path: Path, data: bytes) -> bytes:
    """The one allowed difference: which version of the runtime crates a generated crate asks for."""
    if path.name != "Cargo.toml":
        return data
    return re.sub(rb'(hardroxide-[a-z0-9-]+ = (?:\{ version = )?)"[0-9]+"', rb'\1"N"', data)


def tree(d: Path) -> dict[Path, bytes]:
    return {p.relative_to(d): normalise(p, p.read_bytes()) for p in sorted(d.rglob("*")) if p.is_file()}


def compare_trees(old: Path, new: Path) -> str:
    a, b = tree(old), tree(new)
    out = []
    for p in sorted(set(a) - set(b)):
        out.append(f"missing from the new output: {p}")
    for p in sorted(set(b) - set(a)):
        out.append(f"new file: {p}")
    for p in sorted(set(a) & set(b)):
        if a[p] != b[p]:
            try:
                diff = difflib.unified_diff(a[p].decode().splitlines(), b[p].decode().splitlines(), f"{BASE}/{p}", f"new/{p}", lineterm="", n=1)
                out.extend(list(diff)[:20])
            except UnicodeDecodeError:
                out.append(f"binary file differs: {p}")
    return "\n".join(out)


def help_flags(exe: Path, sub: list[str]) -> tuple[set[str], set[str]]:
    text = run([exe, *sub, "--help"]).stdout
    flags = set(re.findall(r"(?<![\w-])(--[a-z][a-z-]*|-[a-zA-Z])(?=[\s,<])", text))
    commands = set(re.findall(r"^  ([a-z][a-z-]*)\s{2,}", text, re.M)) if not sub else set()
    return flags, commands


def generator():
    old, new = old_cli(), new_cli()
    d = WORK / "generator"
    shutil.rmtree(d, ignore_errors=True)
    compared = refused = 0
    for xsa in sorted((ROOT / "fixtures").rglob("*.xsa")):
        rel = xsa.relative_to(ROOT / "fixtures")
        for platform in PLATFORMS:
            name = "design_x"
            o, n = d / "old" / rel.with_suffix("") / platform, d / "new" / rel.with_suffix("") / platform
            ro = run([old, "generate", xsa, "--platform", platform, "-o", o, "--name", name])
            rn = run([new, "generate", xsa, "--platform", platform, "-o", n, "--name", name])
            if ro.returncode:
                refused += 1  # a design the release could not handle has nothing to stay compatible with
                continue
            if rn.returncode:
                fail(f"generator: {rel} ({platform}) worked in {BASE} and fails now", rn.stderr)
                continue
            diff = compare_trees(o, n)
            if diff:
                fail(f"generator: {rel} ({platform}) differs from {BASE}", diff)
                continue
            # `update` with the same design must accept a crate the release made, and change nothing.
            u = d / "update" / rel.with_suffix("") / platform
            shutil.copytree(o, u)
            ru = run([new, "update", xsa, "-c", u])
            if ru.returncode:
                fail(f"generator: `update` refuses the {BASE} crate for {rel} ({platform})", ru.stdout + ru.stderr)
            elif compare_trees(o, u):
                fail(f"generator: `update` changed the {BASE} crate for {rel} ({platform})", compare_trees(o, u))
            else:
                compared += 1
    if compared:
        ok(f"generator: {compared} design and platform pairs identical to {BASE} and accepted by `update` ({refused} the release could not generate)")
    else:
        fail("generator: nothing was compared")

    old_flags, old_cmds = help_flags(old, [])
    new_flags, new_cmds = help_flags(new, [])
    gone = [f"command {c}" for c in sorted(old_cmds - new_cmds)] + [f"flag {f}" for f in sorted(old_flags - new_flags)]
    for c in sorted(old_cmds - {"help"}):
        gone += [f"`{c} {f}`" for f in sorted(help_flags(old, [c])[0] - help_flags(new, [c])[0])]
    if gone:
        fail("generator: removed from the command line: " + ", ".join(gone))
    else:
        ok(f"generator: all {len(old_cmds)} commands of {BASE} and their flags are still there")


# ---- programs --------------------------------------------------------------------------------------------------------

LINUX_SETS = [(s, f"pynq_z2_{s}.xsa", "design_1") for s in
              "gpio peripherals hls_vadd hls_scale dma_loopback intc mem_uart fifo loopback".split()] + [("base", "real/pynq_base_overlay.xsa", "base")]
BARE_SETS = [("fixtures/board_tests_bm/baremetal_gpio", "baremetal", "pynq_z2_gpio.xsa"),
             ("fixtures/board_tests_bm/baremetal_timer", "baremetal", "pynq_z2_peripherals.xsa"),
             ("fixtures/board_tests_bm/baremetal_dma", "baremetal", "pynq_z2_dma_loopback.xsa"),
             ("fixtures/board_tests_bm/rtos_gpio", "rtos", "pynq_z2_gpio.xsa"),
             ("apps/base/baremetal", "baremetal", "board/pynq_base_overlay.xsa"),
             ("apps/base/rtos", "rtos", "board/pynq_base_overlay.xsa")]
APP_CRATES = [("gfx", True), ("video", False), ("audio", False), ("fat", True), ("net", True), ("crypto", True), ("tls", True)]


def use_working_tree(manifest: Path):
    """What a user does to move a crate to the new libraries, except that the libraries come from this checkout."""
    def path(c):
        return f'path = "{ROOT / "crates" / c}"'
    text = manifest.read_text()
    text = re.sub(r'^(hardroxide-[a-z0-9-]+) = \{ version = "[0-9]+"', lambda m: f"{m[1]} = {{ {path(m[1])}", text, flags=re.M)
    text = re.sub(r'^(hardroxide-[a-z0-9-]+) = "[0-9]+"', lambda m: f"{m[1]} = {{ {path(m[1])} }}", text, flags=re.M)
    manifest.write_text(text)


def programs():
    old = old_cli()
    src = WORK / "frozen-src"
    shutil.rmtree(src, ignore_errors=True)
    src.mkdir(parents=True)
    r = run(["bash", "-c", f"git archive {TAG} apps fixtures/board_tests fixtures/board_tests_bm | tar -x -C '{src}'"], cwd=ROOT)
    if r.returncode or not (src / "apps").is_dir():
        fail(f"programs: cannot read the sources of {TAG} (is the tag fetched?)", r.stderr)
        return
    jobs = [(f"fixtures/board_tests/{s}", "linux", x, name) for s, x, name in LINUX_SETS]
    jobs += [(s, p, x, "design_1") for s, p, x in BARE_SETS]
    for programs_dir, platform, xsa, name in jobs:
        label = f"{programs_dir} ({platform})"
        crate = WORK / "programs" / programs_dir.replace("/", "-")
        shutil.rmtree(crate, ignore_errors=True)
        r = run([old, "generate", ROOT / "fixtures" / xsa, "--platform", platform, "-o", crate, "--name", name])
        if r.returncode:
            fail(f"programs: {label}: the published CLI failed", r.stderr)
            continue
        (crate / "examples").mkdir(exist_ok=True)
        sources = sorted((src / programs_dir).glob("*.rs"))
        for f in sources:
            shutil.copy(f, crate / "examples")
        manifest = crate / "Cargo.toml"
        use_working_tree(manifest)
        text = manifest.read_text()
        if programs_dir.startswith("apps/"):
            for f in (src / "apps" / "base" / "data").glob("*"):
                if f.suffix in (".wav", ".der", ".bin"):
                    shutil.copy(f, crate / "examples")
            extra = "".join(f'hardroxide-{c} = {{ path = "{ROOT / "crates" / ("hardroxide-" + c)}"' + ("" if default else ", default-features = false") + " }\n" for c, default in APP_CRATES)
            extra += f'hardroxide-ps7 = {{ path = "{ROOT / "crates" / "hardroxide-ps7"}", default-features = false, features = ["net"] }}\n'
            text += "\n[dev-dependencies]\n" + extra
        if platform == "linux" and any("wait_async" in f.read_text() for f in sources):
            text = re.sub(r"^(hardroxide-irq = \{ path[^}]*) \}", r'\1, features = ["async"] }', text, flags=re.M)
        manifest.write_text(text + "\n[workspace]\n")
        if platform == "linux":
            cmd = ["cargo", "check", "--examples", "--features", "dev-bitstream"]
        else:
            cmd = ["cargo", "build", "--release", "--examples", "--target", ARM]
        r = run(cmd + ["--manifest-path", manifest, "--target-dir", WORK / "programs-target" / platform])
        if r.returncode:
            errors = "\n".join(l for l in r.stderr.splitlines() if l.startswith(("error", "  -->")))
            fail(f"programs: {label}: the {BASE} programs no longer build", errors or r.stderr)
        else:
            ok(f"programs: {label}: {len(sources)} program(s) of {BASE} build against this tree")


def main():
    checks = {"semver": semver, "generator": generator, "programs": programs}
    wanted = sys.argv[1:] or list(checks)
    if any(w not in checks for w in wanted):
        sys.exit(__doc__)
    WORK.mkdir(parents=True, exist_ok=True)
    for w in wanted:
        checks[w]()
    if failures:
        sys.exit(f"\ncompatibility with {BASE}: {len(failures)} failure(s)")
    print(f"\ncompatible with {BASE}")


if __name__ == "__main__":
    main()
