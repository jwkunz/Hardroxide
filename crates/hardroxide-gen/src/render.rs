/// Hardware smoke-test example for the first AXI GPIO, if the design has one.
pub fn gpio_example(m: &Model, crate_name: &str) -> Option<String> {
    let i = m.insts.iter().find(|i| i.driver == Some("hardroxide_ip::gpio::AxiGpio"))?;
    let p = |k: &str, d: &str| i.inst.parameters.get(k).cloned().unwrap_or_else(|| d.into());
    let w1: u32 = p("C_GPIO_WIDTH", "32").parse().unwrap_or(32).clamp(1, 32);
    let out1 = p("C_ALL_OUTPUTS", "0") == "1";
    let dual = p("C_IS_DUAL", "0") == "1";
    let in2 = p("C_ALL_INPUTS_2", "0") == "1";
    let lib = crate_name.replace('-', "_");
    let mut s = String::from(HEADER);
    let _ = writeln!(s, "//! Hardware smoke test for `{}`: walks a one-hot pattern over channel 1", i.inst.name);
    let _ = writeln!(s, "//! and prints channel 2. Run as root on the board: `cargo run --example gpio_smoke`.\n");
    let _ = writeln!(s, "use hardroxide_ip::gpio::Channel;\nuse std::{{thread::sleep, time::Duration}};\n");
    let _ = writeln!(s, "fn main() -> Result<(), Box<dyn std::error::Error>> {{");
    let _ = writeln!(s, "    let d = {lib}::Design::load()?;");
    let _ = writeln!(s, "    let gpio = &d.{};", i.ident);
    if out1 {
        let _ = writeln!(s, "    gpio.set_input_mask(Channel::One, 0)?; // all outputs");
        let _ = writeln!(s, "    for step in 0..{} {{", w1 * 2);
        let _ = writeln!(s, "        gpio.write(Channel::One, 1 << (step % {w1}))?;");
        if dual && in2 {
            let _ = writeln!(s, "        println!(\"channel 2 inputs: {{:#x}}\", gpio.read(Channel::Two)?);");
        }
        let _ = writeln!(s, "        sleep(Duration::from_millis(250));\n    }}");
        let _ = writeln!(s, "    gpio.write(Channel::One, 0)?;");
    } else {
        let _ = writeln!(s, "    println!(\"channel 1: {{:#x}}\", gpio.read(Channel::One)?);");
    }
    let _ = writeln!(s, "    Ok(())\n}}");
    Some(s)
}
