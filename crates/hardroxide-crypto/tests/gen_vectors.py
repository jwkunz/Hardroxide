#!/usr/bin/env python3
"""Generate vectors.rs: random inputs and the answers of independent implementations (Python's hashlib/hmac and
OpenSSL through the `cryptography` package). Deterministic (seeded), so regenerating gives the same file.
Usage: python3 gen_vectors.py > vectors.rs"""
import hashlib, hmac, random
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature, Prehashed

rnd = random.Random(0x4852584C)
def rb(n): return bytes(rnd.getrandbits(8) for _ in range(n))
h = lambda b: b.hex()
out = ["// Generated by gen_vectors.py: random inputs with the answers of OpenSSL/Python. Do not edit.", ""]

edge = [0, 1, 2, 3, 31, 32, 33, 55, 56, 57, 63, 64, 65, 111, 112, 113, 119, 120, 121, 127, 128, 129, 191, 192, 255, 256, 1000, 4097]
lens = edge + [rnd.randrange(0, 600) for _ in range(120)]

# (message, sha256, sha512)
out.append("pub const HASHES: &[(&str, &str, &str)] = &[")
for n in lens:
    m = rb(n)
    out.append('    ("%s", "%s", "%s"),' % (h(m), hashlib.sha256(m).hexdigest(), hashlib.sha512(m).hexdigest()))
out.append("];\n")

# (key, data, hmac-sha256)
out.append("pub const HMACS: &[(&str, &str, &str)] = &[")
for klen in [0, 1, 20, 32, 63, 64, 65, 100, 131, 200]:
    for dlen in [0, 1, 13, 63, 64, 65, 200]:
        k, d = rb(klen), rb(dlen)
        out.append('    ("%s", "%s", "%s"),' % (h(k), h(d), hmac.new(k, d, hashlib.sha256).hexdigest()))
out.append("];\n")

# (salt, ikm, info, length, okm)
out.append("pub const HKDFS: &[(&str, &str, &str, usize, &str)] = &[")
for _ in range(80):
    salt, ikm, info, n = rb(rnd.choice([0, 0, 13, 32, 64, 77])), rb(rnd.randrange(1, 80)), rb(rnd.choice([0, 5, 33])), rnd.choice([1, 16, 31, 32, 33, 42, 64, 100, 255])
    okm = HKDF(algorithm=hashes.SHA256(), length=n, salt=salt if salt else None, info=info).derive(ikm)
    out.append('    ("%s", "%s", "%s", %d, "%s"),' % (h(salt), h(ikm), h(info), n, h(okm)))
out.append("];\n")

# (key, nonce, aad, plaintext, ciphertext_and_tag)
out.append("pub const AEADS: &[(&str, &str, &str, &str, &str)] = &[")
plens = [0, 1, 15, 16, 17, 31, 32, 33, 63, 64, 65, 127, 128, 129, 1000, 1500]
for pl in plens:
    for al in [0, 1, 12, 16, 17, 40]:
        k, n, a, p = rb(32), rb(12), rb(al), rb(pl)
        out.append('    ("%s", "%s", "%s", "%s", "%s"),' % (h(k), h(n), h(a), h(p), h(ChaCha20Poly1305(k).encrypt(n, p, a))))
for _ in range(60):
    k, n, a, p = rb(32), rb(12), rb(rnd.randrange(0, 70)), rb(rnd.randrange(0, 300))
    out.append('    ("%s", "%s", "%s", "%s", "%s"),' % (h(k), h(n), h(a), h(p), h(ChaCha20Poly1305(k).encrypt(n, p, a))))
out.append("];\n")

# (scalar, u, shared) and (scalar, public)
out.append("pub const X25519S: &[(&str, &str, &str)] = &[")
for _ in range(80):
    a = X25519PrivateKey.from_private_bytes(rb(32))
    b = X25519PrivateKey.from_private_bytes(rb(32))
    raw = lambda k: k.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw, serialization.NoEncryption())
    pub = lambda k: k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    out.append('    ("%s", "%s", "%s"),' % (h(raw(a)), h(pub(b)), h(a.exchange(b.public_key()))))
out.append("];\n")
out.append("pub const X25519PUBS: &[(&str, &str)] = &[")
for _ in range(60):
    a = X25519PrivateKey.from_private_bytes(rb(32))
    out.append('    ("%s", "%s"),' % (h(a.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw, serialization.NoEncryption())),
                                    h(a.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw))))
out.append("];\n")

# (seed, public, message, signature)
out.append("pub const ED25519S: &[(&str, &str, &str, &str)] = &[")
for i in range(70):
    seed = rb(32)
    k = Ed25519PrivateKey.from_private_bytes(seed)
    m = rb([0, 1, 2, 32, 64, 100, 129, 500, 1000][i % 9] if i < 40 else rnd.randrange(0, 400))
    out.append('    ("%s", "%s", "%s", "%s"),' % (h(seed), h(k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)), h(m), h(k.sign(m))))
out.append("];")

# P-256: (private, uncompressed public)
def p256_key():
    while True:
        d = int.from_bytes(rb(32), "big")
        if 1 <= d < 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551:
            return d
def pub65(k): return k.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
out.append("")
out.append("pub const P256KEYS: &[(&str, &str)] = &[")
for d in [1, 2, 3, 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632550] + [p256_key() for _ in range(60)]:
    k = ec.derive_private_key(d, ec.SECP256R1())
    out.append('    ("%064x", "%s"),' % (d, h(pub65(k))))
out.append("];\n")
# (private, sha256 digest, deterministic RFC 6979 signature r||s)
out.append("pub const ECDSA_DET: &[(&str, &str, &str)] = &[")
for i in range(70):
    d = p256_key(); k = ec.derive_private_key(d, ec.SECP256R1())
    m = rb(rnd.randrange(0, 200)); dig = hashlib.sha256(m).digest()
    sig = k.sign(dig, ec.ECDSA(Prehashed(hashes.SHA256()), deterministic_signing=True))
    r, s_ = decode_dss_signature(sig)
    out.append('    ("%064x", "%s", "%064x%064x"),' % (d, h(dig), r, s_))
out.append("];\n")
# (public, digest, ordinary randomised signature r||s) for the verifier
out.append("pub const ECDSA_RANDOM: &[(&str, &str, &str)] = &[")
for i in range(40):
    d = p256_key(); k = ec.derive_private_key(d, ec.SECP256R1())
    dig = hashlib.sha256(rb(rnd.randrange(0, 100))).digest()
    r, s_ = decode_dss_signature(k.sign(dig, ec.ECDSA(Prehashed(hashes.SHA256()))))
    out.append('    ("%s", "%s", "%064x%064x"),' % (h(pub65(k)), h(dig), r, s_))
out.append("];")
print("\n".join(out))
